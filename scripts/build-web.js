'use strict';

// Bundles the simulation modules in src/ into public/engine.js so the
// dashboard can run the whole market in the browser (e.g. on Netlify, which
// serves static files only). Exposes `window.DayTrader = { Engine, ... }`.
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, '..', 'src');
const OUT = path.join(__dirname, '..', 'public', 'engine.js');
const MODULES = ['random', 'indicators', 'market', 'account', 'strategy', 'engine'];

// Minimal stand-in for Node's 'events' module.
const EVENTS_SHIM = `
class EventEmitter {
  constructor() { this._listeners = {}; }
  on(name, fn) { (this._listeners[name] = this._listeners[name] || []).push(fn); return this; }
  emit(name, ...args) { (this._listeners[name] || []).forEach((fn) => fn(...args)); return true; }
}
module.exports = { EventEmitter };`;

function build() {
  const sources = { events: EVENTS_SHIM };
  for (const name of MODULES) sources[name] = fs.readFileSync(path.join(SRC, `${name}.js`), 'utf8');

  const factories = Object.entries(sources)
    .map(([name, code]) => `  ${JSON.stringify(name)}: function (module, exports, require) {\n${code}\n  },`)
    .join('\n');

  const bundle = `// Generated by scripts/build-web.js. Do not edit.
(function (global) {
  'use strict';
  const factories = {
${factories}
  };
  const cache = {};
  function load(name) {
    if (!cache[name]) {
      const module = { exports: {} };
      cache[name] = module;
      factories[name](module, module.exports, (dep) => load(dep.replace(/^\\.\\//, '')));
    }
    return cache[name].exports;
  }
  global.DayTrader = {
    Engine: load('engine').Engine,
    Market: load('market').Market,
    Account: load('account').Account,
    CrossoverBot: load('strategy').CrossoverBot,
  };
})(typeof window !== 'undefined' ? window : globalThis);
`;
  fs.writeFileSync(OUT, bundle);
  return OUT;
}

if (require.main === module) console.log(`Wrote ${path.relative(process.cwd(), build())}`);

module.exports = { build };
